"""M1-R1 workstream D: consolidated economic report, generated ONLY from stored research artefacts
(docs/evidence/m1/*.json) plus benchmark re-runs on the identical stored datasets and costs.
Nothing is edited or filtered: negative findings are included as found.

Usage: python scripts/economic_report.py [--out docs/evidence/m1-r1]
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from datetime import datetime
from decimal import Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_research as rr  # noqa: E402

from asta.research.data.profiles import RuleProfile  # noqa: E402
from asta.research.runner import run_backtest  # noqa: E402
from asta.research.sim.risk import SimRiskLimits  # noqa: E402

EV = Path("docs/evidence/m1")
D = Decimal


def j(name: str):
    return json.loads((EV / name).read_text("utf-8"))


def f2(x, n=2):
    return f"{D(str(x)):,.{n}f}"


def pct(x, n=2):
    return f"{D(str(x)) * 100:,.{n}f}%"


def months(a: str, b: str) -> D:
    da, db = datetime.fromisoformat(a), datetime.fromisoformat(b)
    return D(str((db - da).days)) / D("30.4375")


def md_table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def event_summary(events: list) -> str:
    kinds: dict[str, int] = {}
    for e in events:
        kinds[e[1]] = kinds.get(e[1], 0) + 1
    kinds.pop("DAILY_RESET", None)
    kinds.pop("ORDER_REJECTED", None)
    return ", ".join(f"{k}×{v}" for k, v in sorted(kinds.items())) or "none"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/evidence/m1-r1")
    ap.add_argument("--store", default="data/store")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    base = j("baseline-comparison.json")
    perf = base["performance"]
    rows = {r["name"]: r for r in base["comparison"]["rows"]}
    dr = j("data-report.json")
    sens = j("sensitivity.json")
    hold = j("final-holdout.json")["holdout"]
    wf = {
        (s, v): j(f"walk-forward-{s}-{v}.json")["report"]
        for s in ("regime_grid", "trend_pullback", "sma_cross")
        for v in ("strict_risk_admissible", "net_return_flagged")
    }
    period = (rr.START.isoformat(), rr.END.isoformat())
    full_months = months(*period)

    # ---- benchmark re-runs on the identical stored data / costs / risk limits
    data = rr.load_data(Path(args.store))
    rules_file = sorted(glob.glob("data/import/rules_binance_*.json"))[-1]
    rules = tuple(RuleProfile.from_json(p) for p in json.loads(Path(rules_file).read_text("utf-8")))

    def bench(start: str, end: str) -> dict:
        cfg = rr.base_config(
            data,
            rules,
            "passive_hold",
            {"symbols": list(rr.SYMS), "notional_per_symbol": "100"},
            label="bench",
        ).replace(
            risk=SimRiskLimits.default(),
            warmup_bars=0,
            period_start=datetime.fromisoformat(start),
            period_end=datetime.fromisoformat(end),
        )
        r = run_backtest(cfg, data)
        ret = r.performance.returns
        return {
            "net_pnl": D(str(ret["total_net_pnl"])),
            "fees": D(str(ret["total_fees_quote_equivalent"])),
            "verdict": r.result.risk_verdict,
        }

    hw = hold["regime_grid"]["holdout_window"]
    hold_bench = bench(*hw)
    wf_ref = wf[("regime_grid", "strict_risk_admissible")]
    wins = [w for w in wf_ref["windows"]]
    wf_bench = [bench(*w["test"]) for w in wins]
    wf_bench_sum = sum((b["net_pnl"] for b in wf_bench), D(0))
    wf_bench_breach = sum(1 for b in wf_bench if b["verdict"] == "BREACHED")

    L: list[str] = []
    A = L.append
    A("# ASTA M1 — Consolidated Economic Evaluation (M1-R1 Workstream D)\n")
    A(
        "> **SIMULATED · HISTORICAL DATA · ESTIMATED FILLS · NOT LIVE TRADING.** Nothing below is realised profit. "
        "Generated by `scripts/economic_report.py` from stored artefacts in `docs/evidence/m1/` (unaltered); "
        "benchmark rows for the walk-forward and holdout windows are re-runs of the identical engine on the identical stored data.\n"
    )
    A("## 1. Setup\n")
    A(
        "- **Initial capital:** 1,000 USDT per run (every run, every window). Quote currency USDT; spot only; long-only."
    )
    A(
        f"- **Period:** {period[0][:10]} → {period[1][:10]} (~{f2(full_months, 1)} months), 1-hour candles, BTC-USDT / ETH-USDT / SOL-USDT (Binance public market data)."
    )
    A(
        f"- **Costs (assumed, unverified):** fee schedule `{dr['fees']['schedule_id']}` (maker {dr['fees']['maker_bps']} / taker {dr['fees']['taker_bps']} bps, fee in received asset, no BNB discount); "
        f"slippage model `{dr['execution_model']['version']}` (base {dr['execution_model']['base_slippage_bps']} bps + half-spread {dr['execution_model']['half_spread_bps']} bps + {dr['execution_model']['impact_bps_per_pct']} bps per 1% of bar volume; participation cap {pct(dr['execution_model']['max_participation'], 0)})."
    )
    rl = dr["risk_limits"]
    A(
        f"- **Risk limits (fixed, never relaxed):** {pct(rl['max_asset_pct'], 0)} per asset, {pct(rl['max_total_pct'], 0)} total exposure of starting equity; daily-loss breaker {pct(rl['daily_loss_pct'], 0)}; drawdown halt {pct(rl['max_drawdown_pct'], 0)} of peak equity. A breach is reported as a failed risk budget regardless of P&L.\n"
    )

    A("## 2. Full-period results (3 years, identical data / costs / limits)\n")
    names = [
        ("all_cash", "All cash (benchmark)"),
        ("passive_hold_equal_weight_300", "Passive hold, equal weight 3×100 (benchmark)"),
        ("passive_hold_BTC_only_100", "Passive hold, BTC only 100 (benchmark)"),
        (
            "passive_hold_reference_full_capital",
            "Passive hold 3×333, UNCONSTRAINED reference (not risk-compliant)",
        ),
        ("sma_cross_default", "SMA cross"),
        ("regime_grid_default", "Regime grid"),
        ("trend_pullback_default", "Trend pullback"),
    ]
    tab = []
    for key, label in names:
        p = perf[key]
        r = rows[key]
        trd = p["trading"]
        fills = int(trd["fills"])
        tab.append(
            [
                label,
                f2(r["net_pnl"]),
                pct(r["net_return_pct"]),
                pct(r["max_drawdown_pct"]),
                f2(r["fees"]),
                f2(r["slippage"]),
                str(fills),
                str(trd["closed_round_trips"]),
                f2(D(fills) / full_months, 1),
                pct(p["portfolio"]["avg_exposure_over_equity"], 1),
                pct(p["portfolio"]["max_exposure_over_equity"], 1),
                r["risk_verdict"],
            ]
        )
    A(
        md_table(
            [
                "Run",
                "Net P&L (USDT)",
                "Return",
                "Max drawdown",
                "Fees",
                "Modelled slippage",
                "Fills",
                "Round trips",
                "Fills / month",
                "Avg exposure / equity",
                "Max exposure / equity",
                "Risk budget",
            ],
            tab,
        )
    )
    A(
        "\nFees and slippage are already inside net P&L (net = gross − fees − slippage). 'Exposure' is marked inventory plus open buy-order notional over equity; the unconstrained reference ignores the risk limits by design.\n"
    )

    A("### Inventory at the end of the period\n")
    inv = []
    for key, label in names[1:]:
        p = perf[key]["portfolio"]
        inv.append(
            [
                label,
                f2(p["unrealized_pnl_total"]),
                pct(p["avg_inventory_value_over_equity"], 1),
                pct(p["max_asset_share"], 1),
                ", ".join(f"{a} {f2(v['final_value'])}" for a, v in p["by_asset"].items()),
            ]
        )
    A(
        md_table(
            [
                "Run",
                "Unrealised P&L at end",
                "Avg inventory value / equity",
                "Max single-asset share",
                "Final inventory value by asset (USDT)",
            ],
            inv,
        )
    )
    A(
        "\nStrategies that finish with open inventory carry unrealised (mark-to-market) P&L that is not cash; the liquidation-adjusted equity is in the stored performance reports.\n"
    )

    A("## 3. Risk-limit violations (full period)\n")
    rv = []
    for key, label in names:
        ev = base["risk_events"][key]
        first = next((e for e in ev if e[1] not in ("DAILY_RESET", "ORDER_REJECTED")), None)
        rv.append(
            [
                label,
                rows[key]["risk_verdict"],
                rows[key]["status"],
                event_summary(ev),
                (str(first[0])[:10] + " " + first[1]) if first else "—",
            ]
        )
    A(
        md_table(
            [
                "Run",
                "Verdict",
                "Engine status",
                "Risk events (excl. daily resets / order rejections)",
                "First breach",
            ],
            rv,
        )
    )
    A(
        "\nNote: the unconstrained reference runs with no limits by design and is not a risk-compliant result.\n"
    )

    A("## 4. Walk-forward out-of-sample performance (7 windows, train 270 d / test 90 d)\n")
    w_rows = []
    for (s, v), rep in wf.items():
        pooled = rep["pooled"]
        fees = D(0)
        fills = 0
        for w in rep["windows"]:
            ts = w.get("test_summary")
            if ts:
                fees += D(str(ts["fees"]))
                fills += int(ts["fills"])
        w_rows.append(
            [
                s,
                v,
                f"{pooled['windows_with_params']}/{pooled['windows']}",
                f2(pooled["oos_net_pnl_sum"]),
                pct(pooled["oos_net_return_compounded"]),
                f"{pooled['oos_positive_windows']}/{pooled['windows']}",
                str(pooled["oos_risk_breached_windows"]),
                f2(fees),
                str(fills),
            ]
        )
    A(
        md_table(
            [
                "Strategy",
                "Selection rule",
                "Windows with admissible params",
                "Pooled OOS net P&L (USDT)",
                "Compounded OOS return",
                "Positive windows",
                "Risk-breached OOS windows",
                "OOS fees",
                "OOS fills",
            ],
            w_rows,
        )
    )
    A(
        f"\n**Benchmark over the same 7 test windows** (passive hold 3×100, 1,000 USDT per window): net P&L sum {f2(wf_bench_sum)} USDT; {wf_bench_breach}/{len(wins)} windows breach the risk budget. "
        "'strict_risk_admissible' only lets parameters that kept the TRAINING window inside the risk budget be selected; 'net_return_flagged' maximises training return and flags (but does not exclude) breaches. "
        "In windows with no admissible parameters the strategy holds cash (P&L 0 for that window).\n"
    )

    A("## 5. Final holdout (last 180 days, evaluated exactly once)\n")
    h_rows = []
    for s in ("regime_grid", "trend_pullback", "sma_cross"):
        h = hold[s]
        hs = h["holdout_summary"]
        hp = h["holdout_performance"]
        h_rows.append(
            [
                s,
                f"{h['holdout_window'][0][:10]} → {h['holdout_window'][1][:10]}",
                f2(hs["net_pnl"]),
                pct(hs["net_return_pct"]),
                pct(hs["max_drawdown_pct"]),
                f2(hs["fees"]),
                str(hs["fills"]),
                pct(hp["portfolio"]["avg_exposure_over_equity"], 1),
                hs["risk_verdict"],
            ]
        )
    h_rows.append(
        [
            "passive hold 3×100 (benchmark, same window)",
            f"{hw[0][:10]} → {hw[1][:10]}",
            f2(hold_bench["net_pnl"]),
            pct(hold_bench["net_pnl"] / 1000),
            "—",
            f2(hold_bench["fees"]),
            "—",
            "—",
            hold_bench["verdict"],
        ]
    )
    h_rows.append(
        [
            "all cash (benchmark)",
            f"{hw[0][:10]} → {hw[1][:10]}",
            "0.00",
            "0.00%",
            "0.00%",
            "0.00",
            "0",
            "0.0%",
            "PASSED",
        ]
    )
    A(
        md_table(
            [
                "Strategy",
                "Window",
                "Net P&L (USDT)",
                "Return",
                "Max drawdown",
                "Fees",
                "Fills",
                "Avg exposure / equity",
                "Risk budget",
            ],
            h_rows,
        )
    )
    A(
        "\nParameters were selected on the 12 months before the holdout; the holdout window is consumed (any reuse requires a new validation cycle on fresh data).\n"
    )

    A("## 6. Cost sensitivity (full period, default parameters)\n")
    c_rows = []
    for s in ("sma_cross", "regime_grid", "trend_pullback"):
        sc = {(x["scenario"], x["value"]): x["summary"] for x in sens[s]["scenarios"]}
        c_rows.append(
            [s]
            + [
                f2(sc[k]["net_pnl"]) + ("" if sc[k]["risk_verdict"] == "PASSED" else " (B)")
                for k in [
                    ("fees", "x0"),
                    ("fees", "x1"),
                    ("fees", "x2"),
                    ("fees", "x3"),
                    ("slippage", "x0"),
                    ("slippage", "x2"),
                    ("slippage", "x4"),
                    ("latency_bars", "2"),
                    ("missing_data", "5%"),
                ]
            ]
        )
    A(
        md_table(
            [
                "Strategy",
                "fees ×0",
                "fees ×1",
                "fees ×2",
                "fees ×3",
                "slip ×0",
                "slip ×2",
                "slip ×4",
                "+2 bars latency",
                "5% missing data",
            ],
            c_rows,
        )
    )
    A(
        "\nNet P&L in USDT; '(B)' = risk budget breached in that scenario. Cost effects are path-dependent (not additive): SMA cross and regime grid worsen monotonically as multipliers rise, trend pullback does not. The regime grid's sign changes with small latency / missing-data perturbations, which is an instability, not robustness.\n"
    )

    A("## 7. Data quality and provenance\n")
    d_rows = []
    for sym, d in dr["datasets"].items():
        d_rows.append(
            [
                sym,
                f"{d['period'][0][:10]} → {d['period'][1][:10]}",
                d["timeframe"],
                f"{d['rows']:,}",
                d["provenance"]["root_source_type"],
                d["validation"],
                d["checksum"][:16],
            ]
        )
    A(
        md_table(
            [
                "Symbol",
                "Period",
                "Timeframe",
                "Rows",
                "Root source",
                "Validation",
                "SHA-256 (prefix)",
            ],
            d_rows,
        )
    )
    A(
        f"\nSource: {next(iter(dr['datasets'].values()))['provenance']['parent_source']} (public, unauthenticated; fetched through the egress-checked client; 5-minute candles resampled to 1 hour from complete buckets only, 0 buckets dropped). OKX: no data (upstream DNS block, M0 residual R-1; not bypassed).\n"
    )

    A("## 8. Exchange-specific assumptions\n")
    for a in dr["assumptions"]:
        A(f"- {a}")
    A(
        f"- Rule profile: `{dr['rules'][0]['profile_id']}`-style snapshots retrieved {dr['rules'][0]['retrieved_at'][:10]} (tick/step/min-notional), `verified: false`."
    )
    A(
        "- Fills are estimated from candles only (limit orders need trade-through by ≥1 tick, no queue-priority claim, no intrabar information); real fills would differ."
    )
    A(
        "- Market regime: the period is dominated by rising prices for the three assets; buy-and-hold results reflect that and are not a forecast.\n"
    )

    A("## 9. Why each strategy failed or passed the risk criteria\n")

    def why(key: str, name: str) -> str:
        r = rows[key]
        ev = event_summary(base["risk_events"][key])
        pnl = D(str(r["net_pnl"]))
        sign = "positive" if pnl > 0 else "negative"
        beat = D(str(r["excess_vs_passive_hold"]))
        return (
            f"**{name}** — risk budget **{r['risk_verdict']}** (events: {ev}); net P&L {f2(pnl)} USDT ({sign}), "
            f"{f2(abs(beat) * 1000)} USDT {'above' if beat > 0 else 'below'} equal-weight buy-and-hold; max drawdown {pct(r['max_drawdown_pct'])}; "
            f"fees {f2(r['fees'])} + slippage {f2(r['slippage'])} on {perf[key]['trading']['fills']} fills. Flags: {', '.join(r['flags']) or 'none'}."
        )

    for key, name in names[4:]:
        A("- " + why(key, name))
    A(
        "- **Walk-forward / holdout:** under the strict risk rule regime grid (-35.37) and trend pullback (-74.83) lost out-of-sample; SMA cross's +67.56 comes from the single window where any parameter set was admissible (it held cash in the other six), and its return-maximising variant lost 11.79 with 3 risk-breached windows. In the holdout only SMA cross was positive (+9.60 on 356 fills, a small figure from one window). Profitability is **not established**."
    )
    A(
        "- **Buy-and-hold** also breached the 5% drawdown / 2% daily-loss limits in this period (the assets themselves fell sharply at times), so 'within risk budget' is a stricter test than 'did not lose money'.\n"
    )

    A("## 10. Preserved negative findings\n")
    for t in [
        "Over the full period equal-weight buy-and-hold (+295.02) beat all three active strategies (+160.01, -19.07, -39.38). In the 180-day holdout and in the pooled walk-forward windows, SMA cross did exceed the passive benchmark (+9.60 vs +5.21; +67.56 from one admissible window vs +36.65), while regime grid and trend pullback did not; the passive benchmark itself breached the risk budget in every one of those windows, so these comparisons say little about a usable edge.",
        "Regime grid: negative over the full period (−19.07) and pooled out-of-sample (−35.37; 2 of 7 windows positive); outcome sign flips with +1–2 bars latency or 5% missing data.",
        "Trend pullback: negative everywhere (full −39.38, OOS −74.83 strict / −109.67 flagged, holdout −37.11) and breached the risk budget.",
        "SMA cross: the +160.01 full-period gain breached the risk budget; under the strict rule only 1 of 7 windows had admissible parameters; the flagged variant lost 11.79 OOS with 3 risk-breached windows.",
        "Costs: modelled fees + slippage were "
        + ", ".join(
            f"{k.replace('_default', '')} {f2(D(str(rows[k]['fees'])) + D(str(rows[k]['slippage'])))} (gross trading P&L {f2(D(str(rows[k]['net_pnl'])) + D(str(rows[k]['fees'])) + D(str(rows[k]['slippage'])))})"
            for k in ("sma_cross_default", "regime_grid_default", "trend_pullback_default")
        )
        + " USDT. For SMA cross and regime grid higher fee/slippage multipliers lowered net P&L monotonically; trend pullback was not monotonic (fees x3 -37.70 vs x1 -39.38), and SMA cross at fees x0 was only +1.06 above x1. Runs are path-dependent (a risk halt ends new buying), so cost effects are not additive.",
        "Evidence level for any edge: NONE / WEAK (advisor verdict recorded in the stored studies).",
    ]:
        A(f"- {t}")
    A(
        "\n---\nStatus: this report supports an **ACCEPTANCE CANDIDATE** assessment of the research *engine*; it does not support any claim of strategy profitability."
    )

    (out / "ECONOMIC-REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (out / "economic-benchmarks.json").write_text(
        json.dumps(
            {
                "holdout_passive_hold": {k: str(v) for k, v in hold_bench.items()},
                "walk_forward_passive_hold_sum": str(wf_bench_sum),
                "walk_forward_passive_hold_breached_windows": wf_bench_breach,
            },
            indent=1,
        ),
        encoding="utf-8",
    )
    print("written", out / "ECONOMIC-REPORT.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
